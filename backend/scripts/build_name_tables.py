"""Build frontend/js/names.js from the name tables in backend/app/data/.

Run from backend/ after editing place_names.txt or display_names.py:
    python -m scripts.build_name_tables
A test (tests/test_names.py) fails if names.js is out of date.
"""
from __future__ import annotations

import json
import sys

from app import config
from app.data import display_names as names
from app.services.crop_catalog import ALIASES, clean_name
from app.services.place_names import load, place_key

OUTPUT = config.FRONTEND_DIR / "js" / "names.js"
HEADER = ("/* Generated by backend/scripts/build_name_tables.py from backend/app/data/. Do not edit by hand:\n"
          "   change place_names.txt or display_names.py, then run  python -m scripts.build_name_tables */\n")


def build() -> str:
    table = load()
    entries: list[list[str]] = []
    entry_ids: dict[int, int] = {}
    district_index: dict[str, dict[str, int]] = {}
    for state_key, districts in table["districts"].items():
        index = district_index.setdefault(state_key, {})
        for alias_key, entry in districts.items():
            if id(entry) not in entry_ids:
                entry_ids[id(entry)] = len(entries)
                entries.append([entry["en"], entry["hi"]])
            index[alias_key] = entry_ids[id(entry)]
    crops: dict[str, str] = {}
    for canonical, aliases in ALIASES.items():
        hindi = names.CROP_HI.get(canonical)
        if not hindi:
            continue
        for alias in sorted(aliases | {canonical}):
            crops[clean_name(alias)] = "धान" if ("paddy" in alias or alias == "dhan") else hindi
    data = {
        "states": {key: [value["en"], value["hi"]] for key, value in table["states"].items()},
        "stateAlias": table["state_alias"],
        "districts": entries,
        "districtIndex": district_index,
        "crops": crops,
        "commodities": {clean_name(k): v for k, v in names.COMMODITY_HI.items()},
        "varieties": {clean_name(k): v for k, v in names.VARIETY_HI.items()},
        "grades": {clean_name(k): v for k, v in names.GRADE_HI.items()},
        "seasons": {clean_name(k): v for k, v in names.SEASON_HI.items()},
        "markets": {place_key(k): v for k, v in names.MARKET_HI.items()},
    }
    body = json.dumps(data, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    return f"{HEADER}const NAME_TABLES = {body};\n"


def main(argv=None) -> int:
    text = build()
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT} ({len(text.encode('utf-8')) // 1024} KB).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
