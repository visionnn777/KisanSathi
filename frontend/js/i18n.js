function applyLang(lang) {
  try { localStorage.setItem("lang", lang); } catch (e) { /* private mode: still works for this page */ }
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(node => { node.textContent = t(node.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(node => { node.placeholder = t(node.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-alt]").forEach(node => { node.alt = t(node.dataset.i18nAlt); });
  document.querySelectorAll("[data-i18n-aria]").forEach(node => { node.setAttribute("aria-label", t(node.dataset.i18nAria)); });
  document.querySelectorAll("[data-crop]").forEach(node => { node.textContent = cropLabel(node.dataset.crop); });
  document.querySelectorAll("[data-state-name]").forEach(node => { node.textContent = stateName(node.dataset.stateName); });
  document.querySelectorAll("[data-lang]").forEach(button => {
    button.setAttribute("aria-pressed", String(button.dataset.lang === lang));
  });
  // Make the current section visible in both navigation layouts.
  const currentPage = window.location.pathname.split("/").pop() || "index.html";
  document.querySelectorAll(".top-nav a[href], .bottom-nav a[href]").forEach(link => {
    if (link.getAttribute("href").split("?")[0] === currentPage) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  });
  if (document.body.dataset.titleKey) document.title = `${t(document.body.dataset.titleKey)} | ${t("app_name")}`;
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang } }));
}

document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll("[data-lang]").forEach(button => {
    button.addEventListener("click", () => applyLang(button.dataset.lang));
  });
  applyLang(getLang());
});
