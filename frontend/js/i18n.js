const TL_CONSONANTS = [["chh", "छ"], ["ksh", "क्ष"], ["kh", "ख"], ["gh", "घ"], ["ch", "च"], ["jh", "झ"], ["th", "थ"],
  ["dh", "ध"], ["ph", "फ"], ["bh", "भ"], ["sh", "श"], ["k", "क"], ["g", "ग"], ["c", "क"], ["j", "ज"], ["t", "त"],
  ["d", "द"], ["n", "न"], ["p", "प"], ["b", "ब"], ["m", "म"], ["y", "य"], ["r", "र"], ["l", "ल"], ["v", "व"],
  ["w", "व"], ["s", "स"], ["h", "ह"], ["f", "फ़"], ["z", "ज़"], ["q", "क़"], ["x", "क्स"]];
const TL_VOWELS = [["aa", "ा", "आ"], ["ai", "ै", "ऐ"], ["au", "ौ", "औ"], ["ee", "ी", "ई"], ["ii", "ी", "ई"], ["oo", "ू", "ऊ"],
  ["ou", "ौ", "औ"], ["a", "", "अ"], ["i", "ि", "इ"], ["u", "ु", "उ"], ["e", "े", "ए"], ["o", "ो", "ओ"]];
const TL_NASAL_BEFORE = new Set(["n", "m"]);
const TL_NO_ANUSVARA = new Set(["न", "म", "य", "र", "ल", "व", "ह"]);

function translitWord(word) {
  const w = word.toLowerCase();
  const units = [];
  for (let i = 0; i < w.length;) {
    let matched = false;
    for (const [rom, mark, full] of TL_VOWELS) {
      if (w.startsWith(rom, i)) { units.push({ v: true, rom, mark, full }); i += rom.length; matched = true; break; }
    }
    if (matched) continue;
    for (const [rom, dev] of TL_CONSONANTS) {
      if (w.startsWith(rom, i)) { units.push({ v: false, rom, dev }); i += rom.length; matched = true; break; }
    }
    if (!matched) { units.push({ v: false, rom: w[i], dev: w[i] }); i += 1; }
  }
  let out = "";
  units.forEach((u, idx) => {
    const prev = units[idx - 1];
    const last = idx === units.length - 1;
    if (u.v) {
      if (prev && !prev.v) {
        if (last && u.rom === "a") out += "ा";
        else if (last && u.rom === "i") out += "ी";
        else if (last && u.rom === "u") out += "ू";
        else out += u.mark;
      } else if (prev && prev.v && (prev.rom === "i" || prev.rom === "ee") && (u.rom === "a" || u.rom === "aa")) {
        out += last ? "या" : (u.rom === "aa" ? "या" : "य");
      } else {
        out += u.full;
      }
      return;
    }
    if (prev && !prev.v) {
      const nasal = TL_NASAL_BEFORE.has(prev.rom) && !TL_NO_ANUSVARA.has(u.dev) && idx >= 2;
      if (nasal) out = out.slice(0, -1) + "ं";
      else out += "्";
    }
    out += u.dev;
  });
  return out;
}

