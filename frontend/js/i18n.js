function translitHi(text) {
  if (!text || isHindiText(text)) return text;
  return String(text).replace(/[A-Za-z]+/g, word => {
    const vowels = (word.match(/[aeiou]/gi) || []).length;
    if (word.length >= 2 && word.length <= 5 && word === word.toUpperCase() && vowels <= 1) return word;   // APMC, FAQ
    return NAME_WORDS[word.toLowerCase()] || translitWord(word);
  });
}

function stateKeyOf(name) { return NT.stateAlias[placeKey(name)] || null; }

function stateName(name) {
  if (!name) return name;
  const key = stateKeyOf(name);
  if (key) return NT.states[key][getLang() === "hi" ? 1 : 0];
  return getLang() === "hi" ? translitHi(tidyEnglish(name)) : tidyEnglish(name);
}

function districtEntry(state, name) {
  const key = placeKey(name);
  const stateKey = stateKeyOf(state);
  if (stateKey && NT.districtIndex[stateKey] && key in NT.districtIndex[stateKey]) return NT.districts[NT.districtIndex[stateKey][key]];
  if (!stateKey) {
    for (const index of Object.values(NT.districtIndex)) if (key in index) return NT.districts[index[key]];
  }
  return null;
}

function districtName(state, name) {
  if (!name) return name;
  if (isHindiText(name)) return name;
  const entry = districtEntry(state, name);
  if (entry) return entry[getLang() === "hi" ? 1 : 0];
  return getLang() === "hi" ? translitHi(tidyEnglish(name)) : tidyEnglish(name);
}

/* Mandi names: known towns, then district names, then phonetic Hindi, part by part
   ("Khanna(Ludhiana)" -> "खन्ना(लुधियाना)"). */
function marketName(name, state) {
  if (!name || isHindiText(name)) return name;
  if (getLang() !== "hi") return tidyEnglish(name);
  const whole = NT.markets[placeKey(name)] || (districtEntry(state, name) || [])[1];
  if (whole) return whole;
  return String(name).split(/(\s*[(),/&-]\s*|\s+)/).map(part => {
    if (!part || /^[\s(),/&-]*$/.test(part)) return part;
    return NT.markets[placeKey(part)] || (districtEntry(state, part) || [])[1] || translitHi(part);
  }).join("");
}

/* Crop and commodity names: "Wheat" -> "गेहूँ", "Bengal Gram(Gram)(Whole)" -> "चना". */
function cropLabel(name) {
  if (!name) return name;
  if (getLang() !== "hi") return name;
  if (isHindiText(name)) return name;
  const full = cleanName(name);
  if (NT.commodities[full]) return NT.commodities[full];
  if (CROP_NAMES[name]) return CROP_NAMES[name];
  if (NT.crops[full]) return NT.crops[full];
  const base = cleanName(String(name).split("(")[0]);
  if (NT.commodities[base]) return NT.commodities[base];
  if (NT.crops[base]) return NT.crops[base];
  for (const inside of String(name).match(/\(([^)]*)\)/g) || []) {
    for (const part of inside.slice(1, -1).split(/[/,]/)) {
      const key = cleanName(part);
      if (key && !["whole", "raw", "common"].includes(key) && NT.crops[key]) return NT.crops[key];
    }
  }
  return translitHi(name);
}

function varietyLabel(value) {
  if (!value || getLang() !== "hi" || isHindiText(value)) return value;
  return NT.varieties[cleanName(value)] || cropLabelIfKnown(value)
    || String(value).split(/(\s+|[(),/-])/).map(part => NT.varieties[cleanName(part)] || cropLabelIfKnown(part) || translitHi(part)).join("");
}
function gradeLabel(value) {
  if (!value || getLang() !== "hi" || isHindiText(value)) return value;
  return NT.grades[cleanName(value)] || varietyLabel(value);
}
function cropLabelIfKnown(value) {
  const key = cleanName(value);
  return NT.commodities[key] || NT.crops[key] || null;
}
function seasonLabel(value) {
  if (!value) return value;
  const text = String(value).trim().replace(/\s+/g, " ");
  if (getLang() !== "hi") return text.replace(/\b\w/g, c => c.toUpperCase()).replace(/\bYear\b/, "year");
  return NT.seasons[cleanName(text)] || translitHi(text);
}

