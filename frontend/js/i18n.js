function t(key) {
  const lang = getLang();
  return (TEXT[lang] && TEXT[lang][key]) || TEXT.en[key] || key;
}

/* t() with {placeholders} filled in. */
function tf(key, values = {}) {
  return t(key).replace(/\{(\w+)\}/g, (match, name) => (name in values ? values[name] : match));
}

/* ---------------------------------------------------------------- Names in Hindi
   Data sources keep English names (often old spellings such as "BHATINDA" or "ORISSA").
   NAME_TABLES (js/names.js, built from backend/app/data/) gives each a clean English name and
   its Hindi name. Names that are not in the tables (for example a small mandi) are written
   phonetically in Devanagari so a Hindi reader can still read them. */
const NT = typeof NAME_TABLES !== "undefined" ? NAME_TABLES
  : { states: {}, stateAlias: {}, districts: [], districtIndex: {}, crops: {}, commodities: {}, varieties: {}, grades: {}, seasons: {}, markets: {} };

function placeKey(value) { return String(value || "").toUpperCase().replace(/&/g, "AND").replace(/[^A-Z0-9]/g, ""); }
function cleanName(value) { return String(value || "").toLowerCase().replace(/[^a-z0-9]+/g, " ").trim(); }
function isHindiText(value) { return /[ऀ-ॿ]/.test(String(value || "")); }

/* "LUDHIANA" -> "Ludhiana"; names already in mixed case are kept as typed. */
function tidyEnglish(value) {
  const text = String(value || "").trim().replace(/\s+/g, " ");
  if (!text || text !== text.toUpperCase()) return text;
  return text.toLowerCase().replace(/(^|[\s(\-/.&])([a-z])/g, (m, sep, ch) => sep + ch.toUpperCase());
}

